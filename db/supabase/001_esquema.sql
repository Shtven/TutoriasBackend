-- =====================================================================
-- Sistema de Tutorias — Esquema completo
-- Motor: PostgreSQL 15+ (Supabase)
--
-- Base: TutorConnect.sql (dbdiagram) + cambios recomendados en
-- docs/MODELO_DE_DATOS.md:
--   1. usuario.password_hash (login con contraseña, proveedor = 'LOCAL');
--      proveedor / id_externo quedan de las cuentas de Microsoft/Google
--   2. inscripcion ligada a la tutoria (id_tutoria) en lugar del horario;
--      recordatorio gana id_horario
--   3. catalogo de lugares: tabla aula (edificio, aula) + FK compuesta
--   4. sesion.fecha_aviso_cierre (aviso de lista sin cerrar)
--   5. CHECKs de estados, dias y horas; indices unicos parciales
--
-- !! DESTRUCTIVO !!
-- La seccion 0 elimina las tablas del esquema anterior y del actual,
-- con todos sus datos. Pensado para arrancar una BD nueva (solo habia
-- datos mock). Haz backup si hay algo que conservar.
--
-- Como aplicar en Supabase:
--   Dashboard > SQL Editor > New query > pegar este archivo > Run.
--   (o)  psql "<connection string>" -f db/supabase/001_esquema.sql
--
-- El backend se conecta por JDBC con el usuario `postgres` (dueño de las
-- tablas), que no esta sujeto a RLS. La seccion 5 bloquea el acceso a
-- estas tablas desde la API REST publica de Supabase (roles anon y
-- authenticated), que de otro modo quedarian expuestas con la anon key.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 0. Reset
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS
    recordatorio,
    asistencia,
    sesion,
    inscripcion,
    comentarios,
    temas,
    horario,
    tutoria,
    aula,
    materia,
    usuario,
    permisos,
    rol
CASCADE;

-- ---------------------------------------------------------------------
-- 1. Catalogos
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol     VARCHAR(50) NOT NULL,
    CONSTRAINT ux_rol_rol UNIQUE (rol)
);

-- Experiencia Educativa. identificador = NRC.
CREATE TABLE materia (
    id_materia     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia        VARCHAR(100) NOT NULL,
    identificador  INT          NOT NULL,
    CONSTRAINT ux_materia_identificador UNIQUE (identificador),
    CONSTRAINT ck_materia_identificador CHECK (identificador > 0),
    CONSTRAINT ck_materia_nombre        CHECK (length(btrim(materia)) > 0)
);

-- Lugares donde se imparten tutorias (lista importada de la BD institucional).
CREATE TABLE aula (
    edificio  INT NOT NULL,
    aula      INT NOT NULL,
    CONSTRAINT pk_aula PRIMARY KEY (edificio, aula),
    CONSTRAINT ck_aula_positivos CHECK (edificio > 0 AND aula > 0)
);

-- ---------------------------------------------------------------------
-- 2. Usuarios
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    matricula   VARCHAR(50)  PRIMARY KEY,           -- con prefijo S: S23014587
    nombre      VARCHAR(50)  NOT NULL,
    apellidos   VARCHAR(200) NOT NULL,
    correo      VARCHAR(255) NOT NULL,
    id_rol      INT          NOT NULL,
    proveedor   VARCHAR(20),                        -- LOCAL (contraseña); MICROSOFT | GOOGLE (cuentas anteriores); NULL = pre-registro
    id_externo  VARCHAR(255),                       -- claim 'sub' del proveedor (solo MICROSOFT | GOOGLE)
    password_hash VARCHAR(100),                       -- BCrypt (solo LOCAL)
    CONSTRAINT ux_usuario_correo       UNIQUE (correo),
    CONSTRAINT fk_usuario_rol          FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT ck_usuario_correo_lower CHECK (correo = lower(correo)),
    CONSTRAINT ck_usuario_proveedor    CHECK (proveedor IN ('LOCAL', 'MICROSOFT', 'GOOGLE')),
    CONSTRAINT ck_usuario_credencial   CHECK (
        (proveedor IS NULL     AND id_externo IS NULL     AND password_hash IS NULL)         -- pre-registro
     OR (proveedor = 'LOCAL'   AND id_externo IS NULL     AND password_hash IS NOT NULL)     -- contraseña
     OR (proveedor IN ('MICROSOFT', 'GOOGLE') AND id_externo IS NOT NULL AND password_hash IS NULL)
    ),
    -- Solo hashes BCrypt: evita guardar una contraseña en texto plano al editar a mano.
    CONSTRAINT ck_usuario_password_bcrypt CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);

CREATE UNIQUE INDEX ux_usuario_proveedor_id ON usuario (proveedor, id_externo);
CREATE INDEX ix_usuario_rol ON usuario (id_rol);

-- ---------------------------------------------------------------------
-- 3. Tutorias, horarios y temas
-- ---------------------------------------------------------------------
CREATE TABLE tutoria (
    id_tutoria       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_materia       INT         NOT NULL,
    matricula_tutor  VARCHAR(50) NOT NULL,
    edificio         INT         NOT NULL,
    aula             INT         NOT NULL,
    estado           VARCHAR(50) NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT fk_tutoria_materia FOREIGN KEY (id_materia)       REFERENCES materia (id_materia),
    CONSTRAINT fk_tutoria_tutor   FOREIGN KEY (matricula_tutor)  REFERENCES usuario (matricula),
    CONSTRAINT fk_tutoria_aula    FOREIGN KEY (edificio, aula)   REFERENCES aula (edificio, aula),
    CONSTRAINT ck_tutoria_estado  CHECK (estado IN ('ACTIVA', 'INACTIVA'))
);

CREATE INDEX ix_tutoria_tutor   ON tutoria (matricula_tutor);
CREATE INDEX ix_tutoria_materia ON tutoria (id_materia);
CREATE INDEX ix_tutoria_aula    ON tutoria (edificio, aula);

CREATE TABLE horario (
    id_horario   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tutoria   INT         NOT NULL,
    dia          VARCHAR(50) NOT NULL,
    hora_inicio  TIME        NOT NULL,
    hora_fin     TIME        NOT NULL,
    estado       VARCHAR(50) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT fk_horario_tutoria FOREIGN KEY (id_tutoria) REFERENCES tutoria (id_tutoria),
    CONSTRAINT ck_horario_dia     CHECK (dia IN ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES')),
    CONSTRAINT ck_horario_horas   CHECK (hora_inicio < hora_fin),
    CONSTRAINT ck_horario_estado  CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE INDEX ix_horario_tutoria ON horario (id_tutoria);

CREATE TABLE temas (
    id_tema     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tema        VARCHAR(60) NOT NULL,
    id_horario  INT         NOT NULL,
    CONSTRAINT fk_temas_horario FOREIGN KEY (id_horario) REFERENCES horario (id_horario),
    CONSTRAINT ck_temas_tema    CHECK (length(btrim(tema)) > 0)
);

-- Un tema no se repite dentro del mismo horario (sin distinguir mayusculas).
CREATE UNIQUE INDEX ux_temas_horario_tema ON temas (id_horario, lower(tema));

-- ---------------------------------------------------------------------
-- 4. Inscripciones, sesiones, asistencia, recordatorios, comentarios
-- ---------------------------------------------------------------------
CREATE TABLE inscripcion (
    id_inscripcion      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tutoria          INT         NOT NULL,
    matricula_tutorado  VARCHAR(50) NOT NULL,
    fecha_inscripcion   TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado              VARCHAR(50) NOT NULL DEFAULT 'ACTIVA',
    fecha_baja          TIMESTAMPTZ,
    CONSTRAINT fk_inscripcion_tutoria  FOREIGN KEY (id_tutoria)         REFERENCES tutoria (id_tutoria),
    CONSTRAINT fk_inscripcion_tutorado FOREIGN KEY (matricula_tutorado) REFERENCES usuario (matricula),
    CONSTRAINT ck_inscripcion_estado   CHECK (estado IN ('ACTIVA', 'BAJA', 'BAJA_AUTOMATICA')),
    CONSTRAINT ck_inscripcion_baja     CHECK ((estado = 'ACTIVA') = (fecha_baja IS NULL))
);

-- Una sola inscripcion ACTIVA por tutorado y tutoria (protege contra dobles clics y carreras).
CREATE UNIQUE INDEX ux_inscripcion_activa
    ON inscripcion (id_tutoria, matricula_tutorado) WHERE estado = 'ACTIVA';
CREATE INDEX ix_inscripcion_tutorado ON inscripcion (matricula_tutorado);

-- Ocurrencia de un horario en una fecha. Solo existe al abrir el pase de
-- lista o al cancelar; las sesiones futuras se calculan (virtuales).
CREATE TABLE sesion (
    id_sesion            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_horario           INT  NOT NULL,
    fecha                DATE NOT NULL,
    hora_inicio          TIME NOT NULL,           -- copiada del horario
    hora_fin             TIME NOT NULL,           -- copiada del horario
    fecha_cancelada      TIMESTAMPTZ,
    fecha_lista_abierta  TIMESTAMPTZ,
    fecha_lista_cerrada  TIMESTAMPTZ,
    fecha_aviso_cierre   TIMESTAMPTZ,             -- correo "lista sin cerrar" enviado
    CONSTRAINT fk_sesion_horario       FOREIGN KEY (id_horario) REFERENCES horario (id_horario),
    CONSTRAINT ux_sesion_horario_fecha UNIQUE (id_horario, fecha),
    CONSTRAINT ck_sesion_horas         CHECK (hora_inicio < hora_fin),
    CONSTRAINT ck_sesion_origen        CHECK (fecha_cancelada IS NOT NULL OR fecha_lista_abierta IS NOT NULL),
    CONSTRAINT ck_sesion_cancelada     CHECK (fecha_cancelada IS NULL OR fecha_lista_abierta IS NULL),
    CONSTRAINT ck_sesion_cierre        CHECK (fecha_lista_cerrada IS NULL OR fecha_lista_abierta IS NOT NULL)
);

-- "Sin marca" = no hay fila (asistio es NOT NULL).
CREATE TABLE asistencia (
    id_asistencia   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion       INT     NOT NULL,
    id_inscripcion  INT     NOT NULL,
    asistio         BOOLEAN NOT NULL,
    CONSTRAINT fk_asistencia_sesion      FOREIGN KEY (id_sesion)      REFERENCES sesion (id_sesion),
    CONSTRAINT fk_asistencia_inscripcion FOREIGN KEY (id_inscripcion) REFERENCES inscripcion (id_inscripcion),
    CONSTRAINT ux_asistencia             UNIQUE (id_sesion, id_inscripcion)
);

CREATE INDEX ix_asistencia_inscripcion ON asistencia (id_inscripcion);

CREATE TABLE recordatorio (
    id_recordatorio  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscripcion   INT         NOT NULL,
    id_horario       INT         NOT NULL,
    fecha            DATE        NOT NULL,
    fecha_envio      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_recordatorio_inscripcion FOREIGN KEY (id_inscripcion) REFERENCES inscripcion (id_inscripcion),
    CONSTRAINT fk_recordatorio_horario     FOREIGN KEY (id_horario)     REFERENCES horario (id_horario),
    CONSTRAINT ux_recordatorio             UNIQUE (id_inscripcion, id_horario, fecha)
);

CREATE TABLE comentarios (
    id_comentario       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_tutorado  VARCHAR(50)  NOT NULL,
    comentario          VARCHAR(255) NOT NULL,
    id_tutoria          INT          NOT NULL,
    fecha_comentario    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_comentarios_tutorado FOREIGN KEY (matricula_tutorado) REFERENCES usuario (matricula),
    CONSTRAINT fk_comentarios_tutoria  FOREIGN KEY (id_tutoria)         REFERENCES tutoria (id_tutoria),
    CONSTRAINT ck_comentarios_texto    CHECK (length(btrim(comentario)) > 0)
);

CREATE INDEX ix_comentarios_tutoria ON comentarios (id_tutoria, fecha_comentario DESC);

-- ---------------------------------------------------------------------
-- 5. Supabase: cerrar la API REST publica
-- ---------------------------------------------------------------------
-- RLS activado sin politicas = anon/authenticated no ven ni escriben nada
-- via PostgREST. El backend (usuario postgres, dueño) no se ve afectado.
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'rol', 'materia', 'aula', 'usuario', 'tutoria', 'horario', 'temas',
        'inscripcion', 'sesion', 'asistencia', 'recordatorio', 'comentarios'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;

    -- Los roles anon/authenticated solo existen en Supabase.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated';
        EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated';
    END IF;
END $$;

-- ---------------------------------------------------------------------
-- 6. Datos iniciales
-- ---------------------------------------------------------------------
INSERT INTO rol (rol) VALUES ('TUTORADO'), ('TUTOR'), ('ADMIN');

-- PROVISIONAL: edificios 1-2 con aulas 1-12. Sustituir por la lista real
-- de la BD institucional antes de producción.
INSERT INTO aula (edificio, aula)
SELECT e, a
FROM generate_series(1, 2) AS e, generate_series(1, 12) AS a;

COMMIT;

